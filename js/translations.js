export function translatePage(lang) {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const translation = TRANSLATIONS[lang] && TRANSLATIONS[lang][key];
        if (translation) {
            if (el.tagName === 'TITLE') {
                document.title = translation;
            } else if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = translation;
            } else {
                if (translation.includes('<') && translation.includes('>')) {
                    el.innerHTML = translation;
                } else {
                    el.textContent = translation;
                }
            }
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        const translation = TRANSLATIONS[lang] && TRANSLATIONS[lang][key];
        if (translation) {
            el.placeholder = translation;
        }
    });

    // Sincronizar todos los selectores de idioma en la página
    document.querySelectorAll('#lang-select').forEach(select => {
        select.value = lang;
    });
}

export function initTranslation() {
    // Escuchar cambios en los selectores de idioma
    document.addEventListener('change', (e) => {
        if (e.target && e.target.id === 'lang-select') {
            const selectedLang = e.target.value;
            localStorage.setItem('entreCopasLanguage', selectedLang);
            translatePage(selectedLang);
            
            // Emitir evento para que otros módulos (panel, favoritos, etc.) se enteren del cambio
            document.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: selectedLang } }));
        }
    });

    // Ejecutar traducción inicial al cargar
    const activeLang = localStorage.getItem('entreCopasLanguage') || 'es';
    translatePage(activeLang);
}

